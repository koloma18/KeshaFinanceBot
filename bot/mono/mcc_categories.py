def categorize_by_mcc(mcc: int) -> str:
    """Определить категорию проекта по MCC-коду.

    Args:
        mcc: MCC-код транзакции от Monobank.

    Returns:
        Название категории проекта. Если MCC не найден — "Другое".
    """
    category = MCC_CATEGORIES.get(mcc)
    if category is None:
        logger.info("Неизвестный MCC=%s → категория 'Другое'", mcc)
        return "Другое"
    return category


def get_mcc_description(mcc: int) -> str:
    """Получить русскоязычное описание MCC-кода.

    Args:
        mcc: MCC-код транзакции.

    Returns:
        Описание на русском. Если код не найден — заглушка.
    """
    return MCC_DESCRIPTIONS.get(mcc, f"MCC-{mcc} (неизвестный)")
