def get_toxicity_response(toxicity: str, profanity_enabled: bool = True) -> str:
    """Вернуть фразу в зависимости от уровня токсичности."""
    if toxicity == "soft":
        return random.choice(SOFT_PREFIXES)
    elif toxicity == "hard":
        if not profanity_enabled:
            return random.choice(GRUMPY_PREFIXES)
        return random.choice(HARD_PREFIXES)
    else:
        return random.choice(GRUMPY_PREFIXES)


